  function ThaiBahtText(num) {
    if (num === null || num === undefined || isNaN(num)) return 'ศูนย์บาทถ้วน';
    num = Math.round(Number(num) * 100) / 100;
    if (num === 0) return 'ศูนย์บาทถ้วน';
    const isNeg = num < 0;
    num = Math.abs(num);
    const baht = Math.floor(num);
    const satang = Math.round((num - baht) * 100);
    const digits = ['', 'หนึ่ง', 'สอง', 'สาม', 'สี่', 'ห้า', 'หก', 'เจ็ด', 'แปด', 'เก้า'];

    function readGroup(n) {
      if (n === 0) return '';
      let s = '';
      const str = String(n).padStart(6, '0');
      const vals = str.split('').map(Number);
      if (vals[0]) s += digits[vals[0]] + 'แสน';
      if (vals[1]) s += digits[vals[1]] + 'หมื่น';
      if (vals[2]) s += digits[vals[2]] + 'พัน';
      if (vals[3]) s += digits[vals[3]] + 'ร้อย';
      if (vals[4] === 1) s += 'สิบ';
      else if (vals[4] === 2) s += 'ยี่สิบ';
      else if (vals[4] > 2) s += digits[vals[4]] + 'สิบ';
      if (vals[5] === 1 && vals[4] > 0) s += 'เอ็ด';
      else if (vals[5] === 1 && vals[4] === 0) s += 'หนึ่ง';
      else if (vals[5] > 1) s += digits[vals[5]];
      return s;
    }

    function readNumber(n) {
      if (n === 0) return '';
      let result = '';
      const million = Math.floor(n / 1000000);
      const rest = n % 1000000;
      if (million > 0) result += readGroup(million) + 'ล้าน';
      result += readGroup(rest);
      return result;
    }

    let text = readNumber(baht) + 'บาท';
    if (satang === 0) text += 'ถ้วน';
    else text += readNumber(satang) + 'สตางค์';
    return (isNeg ? 'ลบ' : '') + text;
  }

  function EnglishBahtText(num) {
    if (num === null || num === undefined || isNaN(num)) return 'Zero baht only';
    num = Number(num);
    const isNegative = num < 0;
    const totalSatang = Math.round(Math.abs(num) * 100);
    const baht = Math.floor(totalSatang / 100);
    const satang = totalSatang % 100;
    const ones = ['zero','one','two','three','four','five','six','seven','eight','nine','ten','eleven','twelve','thirteen','fourteen','fifteen','sixteen','seventeen','eighteen','nineteen'];
    const tens = ['', '', 'twenty','thirty','forty','fifty','sixty','seventy','eighty','ninety'];
    const scales = [[1000000000000, 'trillion'], [1000000000, 'billion'], [1000000, 'million'], [1000, 'thousand']];

    function readNumber(n) {
      if (n < 20) return ones[n];
      if (n < 100) return tens[Math.floor(n / 10)] + (n % 10 ? '-' + ones[n % 10] : '');
      if (n < 1000) return ones[Math.floor(n / 100)] + ' hundred' + (n % 100 ? ' ' + readNumber(n % 100) : '');
      for (const [value, name] of scales) {
        if (n >= value) return readNumber(Math.floor(n / value)) + ' ' + name + (n % value ? ' ' + readNumber(n % value) : '');
      }
      return String(n);
    }

    let text = (isNegative ? 'minus ' : '') + readNumber(baht) + ' baht';
    text += satang ? ' and ' + readNumber(satang) + ' satang' : ' only';
    return text.charAt(0).toUpperCase() + text.slice(1);
  }

  function fmtThaiDate(val) {
    if (!val) return '';
    const [y, m, d] = val.split('-');
    return `${parseInt(d)} ${thaiMonths[parseInt(m)-1]} ${parseInt(y)+543}`;
  }

  function fmtDate(val) {
    if (!val) return '';
    if (currentLanguage === 'th') return fmtThaiDate(val);
    const [y, m, d] = val.split('-').map(Number);
    return new Intl.DateTimeFormat('en-GB', {
      day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC'
    }).format(new Date(Date.UTC(y, m - 1, d)));
  }

  function todayBangkok() {
    const parts = new Intl.DateTimeFormat('en-US', {
      timeZone: 'Asia/Bangkok', year: 'numeric', month: '2-digit', day: '2-digit'
    }).formatToParts(new Date());
    const values = Object.fromEntries(parts.map(part => [part.type, part.value]));
    return `${values.year}-${values.month}-${values.day}`;
  }

