  function calcTotal() {
    let subtotal = 0, invalid = false;
    document.querySelectorAll('.item-row').forEach(row => {
      const qty = row.querySelector('.qty-input'), price = row.querySelector('.price-input');
      const amount = Money.line(qty.value, price.value);
      markInvalid(qty, Money.decimal(qty.value,4) === null);
      markInvalid(price, Money.cents(price.value) === null || (amount === null && Money.decimal(qty.value,4) !== null));
      row.querySelector('.item-total').value = amount === null ? '—' : fmt(amount/100);
      if (amount === null) invalid = true; else subtotal += amount;
    });
    const extra = document.getElementById('extraCost'), discount = document.getElementById('discountValue'), rate = document.getElementById('whtRate');
    const extraOn = document.getElementById('showExtraCost').checked;
    const discountOn = document.getElementById('discountEnabled').checked;
    const discountMode = document.getElementById('discountMode').value;
    const whtOn = document.getElementById('showWht').checked && document.getElementById('whtToggle').checked;
    const vatMode = document.getElementById('vatMode').value;
    const extraCents = extraOn ? Money.cents(extra.value) : 0;
    markInvalid(extra, extraCents === null);
    const d = discountMode === 'percent' ? Money.rate(discount.value) : Money.cents(discount.value);
    markInvalid(discount, discountOn && (d === null || (discountMode === 'amount' && d > subtotal)));
    markInvalid(rate, whtOn && Money.rate(rate.value) === null);
    const result = invalid ? null : Money.quote({subtotal, extra:extraCents, discountEnabled:discountOn, discountMode,
      discountValue:discount.value, vatMode, whtRate:whtOn ? rate.value : ''});
    document.getElementById('validation-message').textContent = result ? '' : t('invalid');
    const display = (id, value) => document.getElementById(id).textContent = result ? fmt(value/100) : '—';
    document.getElementById('subTotalDisplay').textContent = invalid ? '—' : fmt(subtotal/100);
    display('discountDisplay', result?.discount); display('baseDisplay', result?.base); display('vatDisplay', result?.vat);
    document.getElementById('vatLabel').textContent = vatMode === 'inclusive' ? (currentLanguage === 'th' ? 'VAT 7% (รวมในราคา)' : 'VAT 7% (included)') : 'VAT 7%';
    document.getElementById('whtDisplay').textContent = result ? (result.wht ? '-' : '') + fmt(result.wht/100) : '—';
    document.getElementById('quoteTotalDisplay').textContent = result ? fmt(result.total/100)+' '+t('currency') : '—';
    document.getElementById('paymentEstimateDisplay').textContent = result ? fmt(result.net/100)+' '+t('currency') : '—';
    document.getElementById('thaiTextDisplay').textContent = result ? '('+(currentLanguage === 'th' ? ThaiBahtText(result.total/100) : EnglishBahtText(result.total/100))+')' : '';
    document.getElementById('rowPaymentEstimate').style.display = whtOn ? '' : 'none';
    document.getElementById('rowWht').classList.toggle('omit-print', !whtOn);
    return !!result;
  }

